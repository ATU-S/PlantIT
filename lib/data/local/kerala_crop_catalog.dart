  static Crop? getById(String id) {
    try {
      return crops.firstWhere((c) => c.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<Crop> search(String query) {
    if (query.trim().isEmpty) return crops;
    final lower = query.toLowerCase();
    return crops.where((c) {
      return c.name.toLowerCase().contains(lower) ||
          c.malayalamName.contains(lower) ||
          c.scientificName.toLowerCase().contains(lower) ||
          c.category.name.toLowerCase().contains(lower);
    }).toList();
  }
